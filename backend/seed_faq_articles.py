import os
import django
import shutil

# Setup Django environment
os.environ.setdefault('DJANGO_SETTINGS_MODULE', 'nubixstore.settings')
django.setup()

from django.contrib.auth.models import User
from shop.models import Article, BlogCategory

# Ensure media folder exists
covers_dir = '/root/NubixShop/public/backend/media/blog/covers'
os.makedirs(covers_dir, exist_ok=True)

# Copy banner images from public to media
public_images = {
    'help_center_banner.jpg': 'help_center_banner.jpg',
    'disable_2fa_banner.jpg': 'disable_2fa_banner.jpg',
    'link_unlink_banner.jpg': 'link_unlink_banner.jpg',
    'account_restriction_banner.jpg': 'account_restriction_banner.jpg',
}

for name, target in public_images.items():
    src = os.path.join('/root/NubixShop/public/images', name)
    dst = os.path.join(covers_dir, target)
    if os.path.exists(src):
        try:
            shutil.copy(src, dst)
            print(f"Copied {name} to {dst}")
        except Exception as e:
            print(f"Error copying {name}: {e}")

