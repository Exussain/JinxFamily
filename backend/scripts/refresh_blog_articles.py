def main():
    updated = 0
    for slug, values in ARTICLES.items():
        article = Article.objects.filter(slug=slug).first()
        if not article:
            print(f"Skipped missing article: {slug}")
            continue
        article.title = values["title"]
        article.summary = values["summary"]
        article.content = values["content"].strip()
        article.save(update_fields=["title", "summary", "content", "updated_at"])
        updated += 1
        print(f"Updated: {slug}")
    print(f"Refreshed {updated} public articles.")


if __name__ == "__main__":
    main()
